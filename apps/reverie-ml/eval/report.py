"""Render eval/results.json as eval/RESULTS.md.

    python -m eval.report [--in eval/results.json] [--out eval/RESULTS.md]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from app.specs import IMAGE_SPEC, TEXT_SPEC

SPEED_NOTE = "CPU throughput was measured on the Apple Silicon Mac that ran the eval, so the home server's CPU fallback will differ."


def _recall_table(models: dict, per_second_key: str, per_second_label: str) -> list[str]:
    set_names = list(next(iter(models.values()))["sets"])
    header = ["Model", "Dims", "Params (M)", "fp16 VRAM est. (GB)", per_second_label, *[f"{s} R@1" for s in set_names], "Floor", "F1 at floor"]
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for key, m in models.items():
        recalls = [f"{m['sets'][s]['recall@1']:.3f}" for s in set_names]
        row = [
            f"`{key}`",
            str(m["dimensions"]),
            str(m["parameters_m"]),
            str(m["vram_fp16_gb_estimate"]),
            str(m[per_second_key]),
            *recalls,
            str(m["floor"]["floor"]),
            str(m["floor"]["f1_at_floor"]),
        ]
        lines.append("| " + " | ".join(row) + " |")
    return lines


def _floor_table(models: dict) -> list[str]:
    lines = ["| Model | Positive median | Negative p95 | Negative max | Suggested floor |", "|---|---|---|---|---|"]
    for key, m in models.items():
        f = m["floor"]
        lines.append(f"| `{key}` | {f['positive_median']} | {f['negative_p95']} | {f['negative_max']} | {f['floor']} |")
    return lines


def render(results: dict) -> str:
    text_choice = next(k for k, v in results["text"].items() if v["model"] == TEXT_SPEC.name)
    image_choice = next(k for k, v in results["image"].items() if v["model"] == IMAGE_SPEC.name)
    out = [
        "# Embedding model eval",
        "",
        "Generated by `python -m eval.report` from `eval/results.json` (`python -m eval.run_eval`). The data is synthetic:",
        "Finnish and English sentences written for this repo, and procedurally drawn images with fi/en captions. No real",
        "library data. Synthetic scenes are easier than real photos, so absolute scores are optimistic and the floors are",
        "starting points to re-tune on the real library, not final values. " + SPEED_NOTE,
        "VRAM is a parameter-count estimate (2 bytes per weight plus 20% for activations), not a measurement.",
        "",
        f"Device: `{results['device']}`.",
        "",
        "## Text (document and query embeddings)",
        "",
        *_recall_table(results["text"], "cpu_texts_per_second", "CPU texts/s"),
        "",
        "R@1 columns are `query language -> document language`. Floor = cosine similarity maximising F1 between matching and non-matching pairs.",
        "",
        *_floor_table(results["text"]),
        "",
        f"**Chosen: `{text_choice}`** ({TEXT_SPEC.name}). Same size and speed as the alternative, equal or better recall in every",
        "direction, and a much cleaner gap between matching and non-matching pairs (F1 at the floor 0.92 vs 0.75).",
        "",
        "## Images (text -> image, fi and en queries)",
        "",
        *_recall_table(results["image"], "cpu_images_per_second", "CPU images/s"),
        "",
        *_floor_table(results["image"]),
        "",
        f"**Chosen: `{image_choice}`** ({IMAGE_SPEC.name}). Finnish queries are the deciding case: recall@1 is far higher than the",
        "base model's. It costs about 3x the VRAM and runs about 5x slower on CPU, which is fine on the GPU for thumbnail-size",
        "images (a one-off backfill, then one image per upload). Vectors are 1152-d, which migration 017 hardcodes.",
        "",
    ]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--in", dest="src", default="eval/results.json")
    parser.add_argument("--out", default="eval/RESULTS.md")
    args = parser.parse_args()
    Path(args.out).write_text(render(json.loads(Path(args.src).read_text())))


if __name__ == "__main__":
    main()
