import { describe, expect, it } from 'vitest';
import { formatDateRange } from './formatting.js';

describe('formatDateRange', () => {
    it.each([
        // Relative presets
        ['today', 'Today'],
        ['yesterday', 'Yesterday'],
        ['last-week', 'This week'],
        ['last-month', 'This month'],
        ['last-year', 'This year'],

        // Whole years
        ['2024', '2024'],
        ['2024-01-01..2024-12-31', '2024'],
        ['2024-01..2024-12', '2024'],
        ['2022-2024', '2022–2024'],
        ['2022-01-01..2024-12-31', '2022–2024'],
        ['2024-2024', '2024'],

        // One whole month
        ['2026-10-01..2026-10-31', 'Oct 2026'],
        ['2026-04-01..2026-04-30', 'Apr 2026'],
        ['2026-01-01..2026-01-31', 'Jan 2026'],
        ['2026-12-01..2026-12-31', 'Dec 2026'],
        ['2024-02-01..2024-02-29', 'Feb 2024'],
        ['2023-02-01..2023-02-28', 'Feb 2023'],
        ['2000-02-01..2000-02-29', 'Feb 2000'],
        ['2100-02-01..2100-02-28', 'Feb 2100'],
        ['2024-06..2024-06', 'Jun 2024'],

        // Several whole months
        ['2024-06-01..2024-08-31', 'Jun–Aug 2024'],
        ['2024-01-01..2024-11-30', 'Jan–Nov 2024'],
        ['2024-02-01..2024-12-31', 'Feb–Dec 2024'],
        ['2024-06..2024-08', 'Jun–Aug 2024'],
        ['2025-12-01..2026-02-28', 'Dec 2025–Feb 2026'],
        ['2023-12-01..2024-02-29', 'Dec 2023–Feb 2024'],
        ['2024-01-01..2025-06-30', 'Jan 2024–Jun 2025'],
        ['2024-03..2025-02', 'Mar 2024–Feb 2025'],

        // A single day
        ['2026-10-03..2026-10-03', 'Oct 3, 2026'],
        ['2026-10-03', 'Oct 3, 2026'],
        ['2026-10-01..2026-10-01', 'Oct 1, 2026'],
        ['2024-02-29', 'Feb 29, 2024'],

        // Not whole months
        ['2026-10-01..2026-10-30', 'Oct 1, 2026 – Oct 30, 2026'],
        ['2026-10-02..2026-10-31', 'Oct 2, 2026 – Oct 31, 2026'],
        ['2026-04-01..2026-04-29', 'Apr 1, 2026 – Apr 29, 2026'],
        ['2024-02-01..2024-02-28', 'Feb 1, 2024 – Feb 28, 2024'],
        ['2024-01-01..2024-12-30', 'Jan 1, 2024 – Dec 30, 2024'],
        ['2024-01-02..2024-12-31', 'Jan 2, 2024 – Dec 31, 2024'],
        ['2025-12-15..2026-01-14', 'Dec 15, 2025 – Jan 14, 2026'],
        // Backwards, so it covers no month
        ['2026-10-01..2026-09-30', 'Oct 1, 2026 – Sep 30, 2026'],

        // Shown as written
        ['2024-2022', '2024-2022'],
        ['2024-08..2024-06', '2024-08..2024-06'],
        ['2024-13..2024-14', '2024-13..2024-14'],
        ['2024-13-01..2024-13-31', '2024-13-01..2024-13-31'],
        ['2026-04-31', '2026-04-31'],
        ['2023-02-29', '2023-02-29'],
        ['2023-02-01..2023-02-29', '2023-02-01..2023-02-29'],
        ['2026-10-00..2026-10-05', '2026-10-00..2026-10-05'],
        ['2024-06-01..', '2024-06-01..'],
        ['soon', 'soon'],
        ['', ''],
    ])('labels %j as %j', (value, label) => {
        expect(formatDateRange(value)).toBe(label);
    });
});
